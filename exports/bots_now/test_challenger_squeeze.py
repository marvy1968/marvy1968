from run_h4_filter_sweep import get_pip_value

def generate_squeeze_signals(df: pd.DataFrame, sym: str) -> pd.DataFrame:
    d = df.copy()
    pip_val = get_pip_value(sym)
    
    # 1. Bollinger Bands (20, 2.0)
    d["bb_mid"] = d["close"].rolling(20).mean()
    d["bb_std"] = d["close"].rolling(20).std(ddof=0)
    d["bb_upper"] = d["bb_mid"] + (2.0 * d["bb_std"])
    d["bb_lower"] = d["bb_mid"] - (2.0 * d["bb_std"])
    
    # 2. True Range & ATR 20
    prev_c = d["close"].shift(1)
    tr = pd.concat([d["high"] - d["low"], (d["high"] - prev_c).abs(), (d["low"] - prev_c).abs()], axis=1).max(axis=1)
    d["atr20"] = tr.rolling(20).mean()
    
    # 3. Keltner Channels (EMA 20, 1.5 * ATR 20)
    d["kc_mid"] = d["close"].ewm(span=20, adjust=False).mean()
    d["kc_upper"] = d["kc_mid"] + (1.5 * d["atr20"])
    d["kc_lower"] = d["kc_mid"] - (1.5 * d["atr20"])
    
    # 4. Squeeze condition (BB strictly inside KC)
    d["is_squeeze"] = (d["bb_upper"] < d["kc_upper"]) & (d["bb_lower"] > d["kc_lower"])
    
    # Count consecutive squeeze bars
    squeeze_run = []
    curr = 0
    for sq in d["is_squeeze"]:
        if sq:
            curr += 1
        else:
            curr = 0
        squeeze_run.append(curr)
    d["squeeze_bars"] = squeeze_run

    signals = []
    # Warm-up requirement
    for i in range(25, len(d) - 1):
        prev = d.iloc[i - 1]
        curr = d.iloc[i]
        next_bar = d.iloc[i + 1]
        
        c = float(curr["close"])
        atr = float(curr["atr20"])
        if pd.isna(atr) or atr <= 0:
            continue
            
        # Armed condition: Squeeze for at least 3 bars up through previous bar
        armed = prev["squeeze_bars"] >= 3
        # Firing condition: Current bar terminates the squeeze (release)
        release = (not curr["is_squeeze"]) and prev["is_squeeze"]
        
        if not (armed and release):
            continue
            
        stop_dist = 2.0 * atr
        stop_pips = stop_dist / pip_val
        if stop_pips < 10.0:
            continue
            
        # Long Release: close breaks above previous BB upper
        if c > float(prev["bb_upper"]):
            signals.append({
                "timestamp": d.index[i + 1],  # Enter on T+1 bar open
                "side": "BUY",
                "stop_pips": stop_pips,
                "target_px": float(next_bar["open"]) + (3.0 * atr),
                "pass_filter": True
            })
            
        # Short Release: close breaks below previous BB lower
        elif c < float(prev["bb_lower"]):
            signals.append({
                "timestamp": d.index[i + 1],  # Enter on T+1 bar open
                "side": "SELL",
                "stop_pips": stop_pips,
                "target_px": float(next_bar["open"]) - (3.0 * atr),
                "pass_filter": True
            })

    return pd.DataFrame(signals)

