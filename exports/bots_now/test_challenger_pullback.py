#!/usr/bin/env python3
import sys
import numpy as np
import pandas as pd
from pathlib import Path

from run_hardened_challenger_framework import (
    verify_canonical_f0_parity,
    build_events_from_signals,
    simulate_h4_portfolio,
    print_portfolio_metrics
)
from run_h4_filter_sweep import get_pip_value

def generate_pullback_signals(df: pd.DataFrame, sym: str) -> pd.DataFrame:
    d = df.copy()
    pip_val = get_pip_value(sym)
    
    # 1. Moving Averages
    d["ema20"] = d["close"].ewm(span=20, adjust=False).mean()
    d["ema50"] = d["close"].ewm(span=50, adjust=False).mean()
    d["sma200"] = d["close"].rolling(200).mean()
    d["sma200_slope"] = d["sma200"] - d["sma200"].shift(5)
    
    # 2. Volatility (ATR 14)
    prev_c = d["close"].shift(1)
    tr = pd.concat([d["high"] - d["low"], (d["high"] - prev_c).abs(), (d["low"] - prev_c).abs()], axis=1).max(axis=1)
    d["atr14"] = tr.rolling(14).mean()

    signals = []
    # Warm-up requirement for 200 SMA + slope
    for i in range(205, len(d)):
        row = d.iloc[i]
        prev = d.iloc[i - 1]
        
        c = float(row["close"])
        o = float(row["open"])
        h = float(row["high"])
        l = float(row["low"])
        atr = float(row["atr14"])
        if pd.isna(atr) or atr <= 0:
            continue
            
        sma = float(row["sma200"])
        slope = float(row["sma200_slope"])
        ema20 = float(row["ema20"])
        ema50 = float(row["ema50"])

        # LONG SETUP: Macro uptrend + EMA stack + Pullback into 20-50 zone + Bullish resumption
        if c > sma and slope > 0 and ema20 > ema50:
            # Previous bar or current bar dipped into the value zone between EMA 20 and EMA 50
            tested_zone = (prev["low"] <= prev["ema20"] and prev["low"] >= prev["ema50"]) or (l <= ema20 and l >= ema50)
            resumed_up = c > o and c > ema20
            
            if tested_zone and resumed_up:
                stop_dist = max(c - ema50, 1.5 * atr)
                stop_pips = stop_dist / pip_val
                if stop_pips >= 10.0:
                    target_px = c + (2.5 * atr)
                    signals.append({
                        "timestamp": d.index[i],
                        "side": "BUY",
                        "stop_pips": stop_pips,
                        "target_px": target_px,
                        "pass_filter": True
                    })

        # SHORT SETUP: Macro downtrend + EMA stack + Pullback into 20-50 zone + Bearish resumption
        elif c < sma and slope < 0 and ema20 < ema50:
            tested_zone = (prev["high"] >= prev["ema20"] and prev["high"] <= prev["ema50"]) or (h >= ema20 and h <= ema50)
            resumed_down = c < o and c < ema20
            
            if tested_zone and resumed_down:
                stop_dist = max(ema50 - c, 1.5 * atr)
                stop_pips = stop_dist / pip_val
                if stop_pips >= 10.0:
                    target_px = c - (2.5 * atr)
                    signals.append({
                        "timestamp": d.index[i],
                        "side": "SELL",
                        "stop_pips": stop_pips,
                        "target_px": target_px,
                        "pass_filter": True
                    })

    return pd.DataFrame(signals)

if __name__ == "__main__":
    # 1. Parity Kill Gate
    verify_canonical_f0_parity()
    
    # 2. Extract Pullback Candidates
    print("=" * 80)
    print("EVALUATING CHALLENGER: H4 TREND PULLBACK (20/50 VALUE ZONE)")
    print("=" * 80)
    pullback_events = build_events_from_signals(generate_pullback_signals, "PULLBACK_H4")
    print(f"Total Raw Trade Candidates Extracted: {len(pullback_events)}")

    if pullback_events.empty:
        print("FATAL: 0 events generated by Pullback strategy.")
        sys.exit(1)

    # 3. Simulate under certified Portfolio 3
    nav_pb, trades_pb = simulate_h4_portfolio(pullback_events, max_positions=3, use_firewall=True)
    print_portfolio_metrics("CHALLENGER: TREND PULLBACK (HARDENED PORTFOLIO 3)", nav_pb, trades_pb)
